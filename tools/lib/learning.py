def _entry_block(root, path, meta, sha):
    """The index block of one entry, in the indexer's format (index skill), built from the file itself."""
    text = common.read_text(path)
    lines = text.split("\n")
    _, body = common.parse_frontmatter(text)
    offset = len(lines) - len(body.split("\n"))
    summary, sections, cur = "", [], None
    for i, line in enumerate(body.split("\n")):
        s = line.strip()
        n = offset + i + 1
        if s.startswith("## "):
            cur = {"title": s[3:].strip(), "start": n, "end": n, "first": ""}
            sections.append(cur)
            continue
        if cur is not None:
            if s:
                cur["end"] = n
                if not cur["first"]:
                    cur["first"] = s.lstrip("-* ").strip()
        elif s and not s.startswith("#") and not s.startswith("Recorded by the agent") and not summary:
            summary = s
    def short(t, n):
        t = " ".join(t.split())
        return t if len(t) <= n else t[:n - 1].rstrip() + "…"
    if not summary:      # no opening paragraph: the Summary section, else the first section that says something
        named = [s for s in sections if s["title"].lower() == "summary" and s["first"]]
        summary = (named or [s for s in sections if s["first"]] or [{"first": ""}])[0]["first"]
    out = ["### " + common.rel(path, root), "<!-- sha256: %s -->" % sha,
           "- type: %s | status: %s | owner: %s | valid_from: %s | origin: %s" % (
               meta.get("type") or "-", entry_status(meta), meta.get("owner") or "-",
               meta.get("valid_from") or "-", meta.get("origin") or "-"),
           "- summary: " + (short(summary, 400) if summary else short(meta.get("name", ""), 400) or "-")]
    if sections:
        out.append("- sections:")
        for s in sections:
            out.append("  - %s (L%d-L%d): %s" % (s["title"], s["start"], s["end"], short(s["first"], 120) or "-"))
    return out


def _heading(line, marks):
    """The text of an index heading written with exactly these marks ("## " or "### "), without the back-ticks or
    spaces a model may have put round a path; "" for any other line."""
    s = line.strip()
    if not s.startswith(marks) or s[len(marks):].startswith("#"):
        return ""
    return s[len(marks):].strip().strip("`").strip()


def sync_knowledge_index(root, entries):
    """Add or refresh the knowledge/INDEX.md block of every entry whose content changed, so an entry the agent
    wrote can be found without a model reading it again. Other blocks (dropped documents, house/, seeds/) are
    the indexer's and are left as they are. Returns the number of blocks written."""
    index = Path(root) / "knowledge" / "INDEX.md"
    if not entries:
        return 0
    if index.exists():
        lines = common.read_text(index).rstrip("\n").split("\n")
    else:
        lines = ["# Knowledge index",
                 "Built by the indexer. Read this before opening knowledge files. Locators: L = lines, p = pages."]
    written = 0
    for path, meta in entries:
        relp = common.rel(path, root)
        sha = common.sha256_file(path)
        start = next((i for i, l in enumerate(lines) if _heading(l, "### ") == relp), None)
        if start is not None:
            end = start + 1
            while end < len(lines) and not lines[end].startswith(("### ", "## ")):
                end += 1
            if any(sha in l for l in lines[start:end]):
                continue
            block = _entry_block(root, path, meta, sha)
            lines[start:end] = block
        else:
            block = _entry_block(root, path, meta, sha)
            folder = "## " + relp.rsplit("/", 1)[0] + "/"
            g = next((i for i, l in enumerate(lines) if _heading(l, "## ").rstrip("/") == folder[3:-1]), None)
            if g is None:
                # a new folder group goes before seeds/ and the closing list, else at the end
                at = next((i for i, l in enumerate(lines)
                           if l.startswith("## seeds/") or l.strip().lower() == "## needs an owner or date"),
                          len(lines))
                lines[at:at] = [folder] + block
            else:
                end = g + 1
                while end < len(lines) and not lines[end].startswith("## "):
                    end += 1
                lines[end:end] = block
        written += 1
    if written:
        common.write_text_atomic(index, "\n".join(lines) + "\n")
    return written

