"""learn-add and learn-index: the learning register, kept by scripts so the agent writes only new lines.

learning/
  index.md                    generated by learn-index: what has been learned, readiness, next steps
  work-types/<slug>.md        evidence about one type of work (the raw material of a skill)
  knowledge-candidates.md     facts about the company noted from the work, waiting for the lawyer's yes
  questions.md                questions for the lawyer that the evidence raised

Evidence line:   <id> | <date> | <matter> | <kind> | <text> | <source> | <origin>
Knowledge line:  <id> | <date> | <type> | <fact> | <source> | <status>
Question line:   <id> | <date> | <about> | <question> | <evidence> | <status>
Ids are <matter or tag>-<n>, unique without coordination: one reader per matter.
"""

import argparse
import datetime as _dt
import re
import sys
from pathlib import Path
from urllib.parse import quote

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

EVIDENCE_COLUMNS = ["id", "date", "matter", "kind", "text", "source", "origin"]
KNOWLEDGE_COLUMNS = ["id", "date", "type", "fact", "source", "status"]
QUESTION_COLUMNS = ["id", "date", "about", "question", "evidence", "status"]
KINDS = ("asked", "did", "position", "fallback", "red-line", "context", "approval", "phrasing", "outcome",
         "timing", "routing", "answer", "note")
POSITION_KINDS = ("position", "fallback", "red-line", "approval")
ORIGINS = ("observed", "stated", "seed", "interview", "lawyer")
KNOWLEDGE_TYPES = ("policy", "entity", "person_role", "standard_answer", "template", "product",
                   "certification", "contract_record", "other")
READY_MATTERS = 3

FENCE = common.FENCE


def ldir(root):
    return Path(root) / "learning"


def ensure_file(path, header_lines):
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        common.write_text_atomic(path, "\n".join(header_lines) + "\n")


def work_type_path(root, slug):
    return ldir(root) / "work-types" / ("%s.md" % slug)


def ensure_work_type(root, slug, name, area, run_date):
    p = work_type_path(root, slug)
    if not p.exists():
        meta = {"work_type": name or slug.replace("-", " ").capitalize(), "slug": slug, "area": area or "",
                "skill": slug, "created": run_date}
        body = "\n".join([FENCE, "",
                          "# %s" % meta["work_type"], "",
                          "## Evidence", "",
                          "# " + " | ".join(EVIDENCE_COLUMNS),
                          "# kinds: " + ", ".join(KINDS),
                          "# origin: observed (a matter), stated (someone said it is the rule), seed (Harvey or "
                          "other extraction), interview, lawyer (said in chat)", ""])
        common.write_text_atomic(p, common.render_frontmatter(meta, body))
    return p


def next_ids(path, prefix):
    """Next free number for ids starting with <prefix>- in a pipe file."""
    high = 0
    if path.exists():
        for line in common.read_text(path).split("\n"):
            m = re.match(r"^" + re.escape(prefix) + r"-(\d+)\s*\|", line.strip())
            if m:
                high = max(high, int(m.group(1)))
    return high + 1


def read_stdin_lines():
    return [l.rstrip("\n") for l in sys.stdin.read().split("\n") if l.strip() and not l.strip().startswith("#")]


def add_main(argv=None):
    ap = argparse.ArgumentParser(prog="bash tools/learn-add",
                                 description="Append learning lines (read from stdin, one per line).")
    ap.add_argument("--matter", required=True, help="matter reference, or a tag such as seed or chat")
    ap.add_argument("--work-type", metavar="SLUG", help="work type slug (evidence lines)")
    ap.add_argument("--work-type-name", default="", help="display name when the work type is new")
    ap.add_argument("--area", default="")
    ap.add_argument("--knowledge", action="store_true", help="lines are: type | fact | source")
    ap.add_argument("--question", action="store_true", help="lines are: about | question | evidence")
    ap.add_argument("--origin", default="observed", help="default origin for evidence lines")
    ap.add_argument("--date", help="YYYY-MM-DD (default: the run's date, else today, house time)")
    ap.add_argument("--run", metavar="RUN", help="the run id (YYYY-MM-DD_HHMMSS); its date is the default --date")
    a = ap.parse_args(argv)
    root = common.find_root()
    run_date = a.run[:10] if a.run and re.match(r"^\d{4}-\d{2}-\d{2}(_|$)", a.run) else ""
    today = a.date or run_date or common.now_house(root).date().isoformat()
    tag = re.sub(r"[^A-Za-z0-9-]", "", a.matter) or "x"
    lines = read_stdin_lines()
    if not lines:
        common.die("learn-add: no lines on stdin", 2)
    added, refused = [], []
    if a.knowledge:
        path = ldir(root) / "knowledge-candidates.md"
        ensure_file(path, [FENCE, "# Facts about the company noted from the work. Written to knowledge/ only after "
                           "the lawyer's yes.", "# " + " | ".join(KNOWLEDGE_COLUMNS),
                           "# status: pending, confirmed (knowledge/<file>), rejected"])
        n = next_ids(path, "K-" + tag)
        for l in lines:
            f = common.split_pipe(l)
            if len(f) < 3 or f[0] not in KNOWLEDGE_TYPES or not f[1]:
                refused.append(l)
                continue
            common.append_line(path, common.join_pipe(["K-%s-%d" % (tag, n), today, f[0], f[1], f[2], "pending"]))
            added.append("K-%s-%d" % (tag, n))
            n += 1
    elif a.question:
        path = ldir(root) / "questions.md"
        ensure_file(path, [FENCE, "# Questions for the lawyer raised by the evidence.",
                           "# " + " | ".join(QUESTION_COLUMNS), "# status: open, answered (<date>)"])
        n = next_ids(path, "Q-" + tag)
        for l in lines:
            f = common.split_pipe(l)
            if len(f) < 2 or not f[1]:
                refused.append(l)
                continue
            common.append_line(path, common.join_pipe(["Q-%s-%d" % (tag, n), today, f[0], f[1],
                                                       f[2] if len(f) > 2 else a.matter, "open"]))
            added.append("Q-%s-%d" % (tag, n))
            n += 1
    else:
        if not a.work_type or not re.match(r"^[a-z0-9][a-z0-9-]*$", a.work_type):
            common.die("learn-add: --work-type SLUG (lowercase, hyphens) is required for evidence lines", 2)
        if a.origin not in ORIGINS:
            common.die("learn-add: --origin must be one of " + ", ".join(ORIGINS), 2)
        path = ensure_work_type(root, a.work_type, a.work_type_name, a.area, today)
        n = next_ids(path, tag)
        for l in lines:
            f = common.split_pipe(l)
            if len(f) < 2 or f[0] not in KINDS or not f[1]:
                refused.append(l)
                continue
            origin = f[3] if len(f) > 3 and f[3] in ORIGINS else a.origin
            common.append_line(path, common.join_pipe(["%s-%d" % (tag, n), today, a.matter, f[0], f[1],
                                                       f[2] if len(f) > 2 else "", origin]))
            added.append("%s-%d" % (tag, n))
            n += 1
    print("learn-add: %d added%s" % (len(added), (", %d refused" % len(refused)) if refused else ""))
    for l in refused:
        print("refused (check the kind or type and the fields): " + l)
    return 1 if refused else 0

