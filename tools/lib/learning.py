def _int(v):
    try:
        return int(str(v).strip())
    except (TypeError, ValueError):
        return None


WRITTEN_RE = r"\.(\d{4}-\d{2}-\d{2}_\d{6})(?:_(\d+))?\.written"


def latest_written(path):
    """The file as the agent last wrote it: the newest history/<stem>.<stamp>[_N].written<ext> beside it, kept by
    the after-write hook or by learn-mark --wrote. None when there is none. Other copies in history/ (a manual
    history-copy, a .before copy of the lawyer's version) are never taken for the agent's version."""
    path = Path(path)
    hist = path.parent / "history"
    if not hist.is_dir():
        return None
    ext = path.suffix or ".md"
    pat = re.compile(r"^" + re.escape(path.stem) + WRITTEN_RE + re.escape(ext) + r"$")
    best = None
    for p in hist.iterdir():
        m = pat.match(p.name)
        if m:
            key = (m.group(1), int(m.group(2) or 1))
            if best is None or key > best[0]:
                best = (key, p)
    return best[1] if best else None


def keep_written(path, when=None):
    """Copy the file to history/<stem>.<stamp>.written<ext> (what the after-write hook does). Returns the copy."""
    import shutil
    path = Path(path)
    hist = path.parent / "history"
    hist.mkdir(exist_ok=True)
    stamp = (when or _dt.datetime.now()).strftime("%Y-%m-%d_%H%M%S")
    ext = path.suffix or ".md"
    dest = hist / ("%s.%s.written%s" % (path.stem, stamp, ext))
    n = 2
    while dest.exists():
        dest = hist / ("%s.%s_%d.written%s" % (path.stem, stamp, n, ext))
        n += 1
    shutil.copy2(common.os_path(path), common.os_path(dest))
    return dest


def hand_edited(path):
    """True when the file no longer reads as the agent last wrote it. None when there is no copy to compare with."""
    prev = latest_written(path)
    if prev is None:
        return None
    return common.read_text(prev).rstrip() != common.read_text(path).rstrip()


def skill_info(root, slug, area):
    cands = ([Path(root) / "skills" / area / slug / "SKILL.md"] if area else []) + \
        sorted((Path(root) / "skills").glob("*/%s/SKILL.md" % slug))
    for cand in cands:
        if cand.is_file() and cand.parent.parent.name != "operations":
            meta, _ = common.read_frontmatter_file(cand)
            status = (meta.get("status") or "working").lower()
            return {"path": cand, "rel": common.rel(cand, root),
                    "status": "approved" if status == "approved" else "working",
                    "version": meta.get("version", "") or "0",
                    "written": meta.get("written", "") or meta.get("last_reviewed", ""),
                    "evidence_lines": _int(meta.get("evidence_lines")),
                    "edited": hand_edited(cand)}
    return None


def entry_status(meta):
    s = (meta.get("status") or "").lower()
    if s in ("working", "approved"):
        return s
    return "approved" if meta.get("confirmed_by") else "working"


def entry_files(root):
    """(path, frontmatter) of every knowledge entry: a Markdown file under knowledge/ with a type in its
    frontmatter. Dropped originals, the index, the type lists and history/ copies are not entries."""
    base = Path(root) / "knowledge"
    out = []
    if not base.is_dir():
        return out
    for p in sorted(base.rglob("*.md")):
        parts = p.relative_to(base).parts
        if "history" in parts[:-1] or p.name in NOT_ENTRIES:
            continue
        meta, _ = common.read_frontmatter_file(p)
        if meta.get("type"):
            out.append((p, meta))
    return out


def interview_date(root, slug, name):
    d = Path(root) / "seeds" / "interviews"
    if not d.is_dir():
        return ""
    keys = {slug, slug.replace("-", " "), (name or "").lower().replace(" ", "-")}
    dates = []
    for f in d.glob("*.notes.md"):
        low = f.name.lower()
        if any(k and k in low for k in keys):
            dates.append(f.name[:10])
    return max(dates) if dates else ""


