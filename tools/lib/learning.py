def parse_work_type(path):
    meta, _ = common.read_frontmatter_file(path)
    ev = common.read_pipe_records(path, EVIDENCE_COLUMNS)
    ev = [e for e in ev if re.match(r"^[A-Za-z0-9-]+-\d+$", e["id"])]
    return meta, ev


def skill_state(root, slug, area):
    for cand in ([Path(root) / "skills" / area / slug / "SKILL.md"] if area else []) + \
            sorted((Path(root) / "skills").glob("*/%s/SKILL.md" % slug)):
        if cand.is_file():
            meta, _ = common.read_frontmatter_file(cand)
            return (meta.get("status") or "draft").lower(), common.rel(cand, root)
    return "none", ""


def interview_date(root, slug, name):
    d = Path(root) / "seeds" / "interviews"
    if not d.is_dir():
        return ""
    keys = {slug, slug.replace("-", " "), (name or "").lower().replace(" ", "-")}
    dates = []
    for f in d.glob("*.notes.md"):
        low = f.name.lower()
        if any(k and k in low for k in keys):
            dates.append(f.name[:10])
    return max(dates) if dates else ""


def link(p):
    return quote(p, safe="/")


def index_main(argv=None):
    ap = argparse.ArgumentParser(prog="bash tools/learn-index",
                                 description="Rebuild learning/index.md: what has been learned, readiness, next steps.")
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--run", metavar="RUN", help="the run id; every tool accepts it (not used here)")
    a = ap.parse_args(argv)
    root = common.find_root()
    base = ldir(root)
    (base / "work-types").mkdir(parents=True, exist_ok=True)
    rows = []
    for p in sorted((base / "work-types").glob("*.md")):
        meta, ev = parse_work_type(p)
        slug = meta.get("slug") or p.stem
        name = meta.get("work_type") or slug
        area = meta.get("area", "")
        matters = {e["matter"] for e in ev if common.REF_RE.match(e["matter"] or "")}
        positions = [e for e in ev if e["kind"] in POSITION_KINDS]
        seeds = [e for e in ev if e["origin"] == "seed"]
        skill, skill_file = skill_state(root, meta.get("skill") or slug, area)
        interview = interview_date(root, slug, name)
        if skill == "approved":
            ready = "skill approved"
        elif skill != "none":
            ready = "draft skill waiting for your approval"
        elif len(matters) >= READY_MATTERS and positions and interview:
            ready = "ready to draft the skill"
        elif len(matters) >= READY_MATTERS and positions:
            ready = "ready for an interview"
        elif len(matters) + (1 if seeds else 0) >= 1:
            ready = "collecting evidence (%d of %d matters)" % (len(matters), READY_MATTERS)
        else:
            ready = "no evidence yet"
        rows.append({"slug": slug, "name": name, "area": area, "file": p, "matters": len(matters),
                     "evidence": len(ev), "positions": len(positions), "seeds": len(seeds),
                     "interview": interview, "skill": skill, "skill_file": skill_file, "ready": ready})
    kc = common.read_pipe_records(base / "knowledge-candidates.md", KNOWLEDGE_COLUMNS)
    kc_pending = [k for k in kc if k["status"].startswith("pending")]
    qs = common.read_pipe_records(base / "questions.md", QUESTION_COLUMNS)
    q_open = [q for q in qs if q["status"].startswith("open")]
    steps = []
    if kc_pending:
        steps.append("Confirm the facts noted about the company: %d waiting. Say \"learn\"." % len(kc_pending))
    if q_open:
        steps.append("Answer the open questions: %d waiting. Say \"learn\"." % len(q_open))
    for r in sorted(rows, key=lambda r: -r["matters"]):
        if r["ready"] == "ready for an interview":
            steps.append("Interview about %s (%d matters so far): say \"interview me about %s\"."
                         % (r["name"], r["matters"], r["name"]))
    for r in sorted(rows, key=lambda r: -r["matters"]):
        if r["ready"] == "ready to draft the skill":
            steps.append("Draft the %s skill: say \"draft a skill for %s\"." % (r["name"], r["name"]))
        elif r["ready"].startswith("draft skill"):
            steps.append("Read and approve the draft %s skill (%s)." % (r["name"], r["skill_file"]))
    stamp = common.stamp(root)
    L = ["# What the system has learned", "",
         "_Rebuilt by tools/learn-index on %s. Do not edit this page._" % stamp, "",
         "## Work types", ""]
    if rows:
        L += ["| Work type | Matters | Evidence lines | Positions | From seeds | Interview | Skill | Where it stands |",
              "|---|---|---|---|---|---|---|---|"]
        for r in sorted(rows, key=lambda r: (-r["matters"], r["name"].lower())):
            L.append("| [%s](work-types/%s) | %d | %d | %d | %d | %s | %s | %s |" % (
                r["name"], link(r["file"].name), r["matters"], r["evidence"], r["positions"], r["seeds"],
                r["interview"] or "none", r["skill"], r["ready"]))
    else:
        L.append("None yet. Evidence appears here as matters are read.")
    L += ["", "## Facts about the company, waiting for your yes", ""]
    L += ["- %s (%s): %s" % (k["id"], k["type"], k["fact"]) for k in kc_pending] or ["None."]
    if kc_pending:
        L += ["", "Details: [knowledge-candidates.md](knowledge-candidates.md)"]
    L += ["", "## Open questions", ""]
    L += ["- %s (%s): %s" % (q["id"], q["about"], q["question"]) for q in q_open] or ["None."]
    L += ["", "## Next learning steps", ""]
    L += ["%d. %s" % (i + 1, s) for i, s in enumerate(steps)] or ["Nothing waiting. Keep dropping emails, including your sent items."]
    common.write_text_atomic(base / "index.md", "\n".join(L) + "\n")
    if not a.quiet:
        print("learn-index: %d work types, %d facts waiting, %d open questions; learning/index.md rebuilt"
              % (len(rows), len(kc_pending), len(q_open)))
        for i, s in enumerate(steps):
            print("%d. %s" % (i + 1, s))
    return 0


if __name__ == "__main__":
    tool = sys.argv[1] if len(sys.argv) > 1 else ""
    if tool == "add":
        sys.exit(add_main(sys.argv[2:]))
    if tool == "index":
        sys.exit(index_main(sys.argv[2:]))
    common.die("usage: learning.py add|index ...", 2)
