def mark_main(argv=None):
    ap = argparse.ArgumentParser(prog="bash tools/learn-mark",
                                 description="Set the status of fact lines (K-...) and open points (Q-...).")
    ap.add_argument("ids", nargs="?", default="",
                    help="ids, comma-separated: K-... in knowledge-candidates.md, Q-... in questions.md")
    ap.add_argument("--wrote", nargs="+", metavar="FILE",
                    help="without hooks: record that the agent has just written these legal skills or knowledge "
                         "entries (a copy of each goes to history/ as the agent's version)")
    ap.add_argument("--status",
                    help='for example "written (knowledge/entities/example-gmbh.md)", "dropped (duplicate of '
                         'K-2026-0001-2)", "settled (2026-11-20): we ask every time (2026-0042, 2026-0051)"')
    ap.add_argument("--run", metavar="RUN", help="the run id; every tool accepts it (not used here)")
    a = ap.parse_args(argv)
    root = common.find_root()
    if a.wrote:
        if a.ids or a.status:
            common.die("learn-mark: --wrote takes files only", 2)
        rc = 0
        for f in a.wrote:
            p = Path(f) if Path(f).is_absolute() else Path(root) / f
            if not p.is_file():
                print("no file: " + f)
                rc = 1
                continue
            print(common.rel(keep_written(p), root))
        return rc
    ids = [i for i in re.split(r"[,\s]+", a.ids.strip()) if i]
    status = " ".join((a.status or "").split()).replace(" | ", " / ")
    if not ids or not status:
        common.die("learn-mark: give at least one id and a --status", 2)
    files = {"K-": (ldir(root) / "knowledge-candidates.md", KNOWLEDGE_COLUMNS),
             "Q-": (ldir(root) / "questions.md", QUESTION_COLUMNS)}
    bad = [i for i in ids if i[:2] not in files]
    if bad:
        common.die("learn-mark: ids start with K- (facts) or Q- (open points): " + ", ".join(bad), 2)
    found = set()
    for prefix, (path, columns) in files.items():
        want = {i for i in ids if i.startswith(prefix)}
        if not want or not path.exists():
            continue
        out, changed = [], False
        for line in common.read_text(path).split("\n"):
            if common.is_record_line(line):
                f = common.split_pipe(line)
                if f[0] in want:
                    f = (f + [""] * len(columns))[:len(columns) - 1] + [status]
                    line = common.join_pipe(f)
                    found.add(f[0])
                    changed = True
            out.append(line)
        if changed:
            common.write_text_atomic(path, "\n".join(out))
    missing = [i for i in ids if i not in found]
    print("learn-mark: %d marked%s" % (len(found), (", %d not found" % len(missing)) if missing else ""))
    for i in missing:
        print("not found: " + i)
    return 1 if missing else 0

