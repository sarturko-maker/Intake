"""learn-add, learn-mark and learn-index: the learning register, kept by scripts so the agent writes only new lines.

learning/
  index.md                    generated by learn-index: skills, knowledge, open points, what the next pass will do
  work-types/<slug>.md        evidence about one type of work (the raw material of its skill)
  knowledge-candidates.md     facts about the company noted from the work; the learning pass writes them up
  questions.md                points the evidence left open; the learning pass settles what later evidence answers

Evidence line:   <id> | <date> | <matter> | <kind> | <text> | <source> | <origin>
Fact line:       <id> | <date> | <type> | <fact> | <source> | <status>
Open point line: <id> | <date> | <about> | <question> | <evidence> | <status>
Ids are <matter or tag>-<n>, unique without coordination: one reader per matter.

Nothing here waits for the lawyer. A skill (skills/<area>/<slug>/SKILL.md) and a knowledge entry are the
agent's working view until the lawyer approves them; learn-index says which ones the next learning pass
should write or rewrite, and keeps knowledge/INDEX.md in step with the entries.
"""

