"""Tests for tools/skills-sync (spec D13)."""

import shutil
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from wsfixture import ROOT, Workspace  # noqa: E402

MARKER = "Generated by tools/skills-sync from skills/. Do not edit."


def tree(d):
    d = Path(d)
    return {p.relative_to(d).as_posix(): p.read_bytes() for p in d.rglob("*") if p.is_file()}


class SkillsSyncTest(unittest.TestCase):
    def setUp(self):
        self.ws = Workspace(skills=False)
        ws = self.ws
        ws.write("skills/POINTERS.md", "# Pointers\n")
        ws.write("skills/operations/intake/SKILL.md", "---\nname: intake\n---\n# Intake\n")
        ws.write("skills/operations/intake/notes/order.md", "oldest first\n")
        ws.write("skills/operations/bundle/SKILL.md", "---\nname: bundle\n---\n# Bundle\n")
        ws.write("skills/commercial/nda-review/SKILL.md", "---\nname: nda-review\n---\n# NDA review\n")
        ws.write("skills/commercial/nda-review/templates/reply.md", "Dear {{name}}\n")
        ws.write("skills/commercial/drafts-only/README.md", "no SKILL.md, so not a skill\n")
        self.mirror = ws.root / ".claude" / "skills"

    def tearDown(self):
        self.ws.cleanup()

    def sync(self, *args):
        return self.ws.run("skills-sync", *args)

    def test_mirrors_every_skill_and_writes_the_marker(self):
        r = self.sync()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("3 skills mirrored to .claude/skills/", r.stdout)
        self.assertEqual(sorted(p.name for p in self.mirror.iterdir() if p.is_dir()),
                         ["bundle", "intake", "nda-review"])
        self.assertEqual(tree(self.mirror / "nda-review"), tree(self.ws.root / "skills/commercial/nda-review"))
        self.assertEqual(tree(self.mirror / "intake"), tree(self.ws.root / "skills/operations/intake"))
        self.assertEqual((self.mirror / ".generated").read_text(), MARKER + "\n")
        self.assertFalse((self.mirror / "drafts-only").exists())
        self.assertFalse((self.mirror / "POINTERS.md").exists())

    def test_check_passes_after_sync_and_writes_nothing(self):
        self.sync()
        before = tree(self.mirror)
        r = self.sync("--check")
        self.assertEqual(r.returncode, 0, r.stdout)
        self.assertIn("matches skills/ (3 skills)", r.stdout)
        self.assertEqual(tree(self.mirror), before)

    def test_check_finds_every_kind_of_difference(self):
        r = self.sync("--check")
        self.assertEqual(r.returncode, 1)
        self.assertIn("missing: .claude/skills/intake", r.stdout)
        self.assertFalse(self.mirror.exists(), "--check never writes")
        self.sync()
        (self.mirror / "intake" / "SKILL.md").write_text("edited by hand\n")
        (self.mirror / "stale").mkdir()
        (self.mirror / "stale" / "SKILL.md").write_text("old\n")
        (self.mirror / ".generated").unlink()
        self.ws.write("skills/operations/bundle/extra.md", "new file in canonical\n")
        r = self.sync("--check")
        self.assertEqual(r.returncode, 1)
        for line in ("differs: .claude/skills/intake (canonical: skills/operations/intake)",
                     "differs: .claude/skills/bundle (canonical: skills/operations/bundle)",
                     "extra: .claude/skills/stale (no canonical skill in skills/)",
                     "marker: .claude/skills/.generated is missing or changed"):
            self.assertIn(line, r.stdout)
        self.assertIn("4 difference(s)", r.stdout)

    def test_sync_replaces_changed_skills_and_removes_stale_ones(self):
        self.sync()
        (self.mirror / "intake" / "SKILL.md").write_text("edited by hand\n")
        (self.mirror / "intake" / "leftover.md").write_text("not in canonical\n")
        (self.mirror / "stale").mkdir()
        r = self.sync()
        self.assertEqual(r.returncode, 0, r.stdout)
        self.assertIn("updated: intake", r.stdout)
        self.assertIn("removed: stale", r.stdout)
        self.assertEqual(tree(self.mirror / "intake"), tree(self.ws.root / "skills/operations/intake"))
        self.assertFalse((self.mirror / "stale").exists())
        self.assertEqual(self.sync("--check").returncode, 0)
        self.assertIn("no changes", self.sync().stdout)

    def test_name_clash_exits_2_and_writes_nothing(self):
        self.ws.write("skills/commercial/intake/SKILL.md", "# a second intake\n")
        r = self.sync()
        self.assertEqual(r.returncode, 2)
        self.assertIn("name clash: skills/commercial/intake and skills/operations/intake", r.stderr)
        self.assertFalse(self.mirror.exists())
        self.assertEqual(self.sync("--check").returncode, 2)

    def test_group_that_is_not_an_area_is_mirrored_with_a_warning(self):
        self.ws.write("skills/marketing/blog/SKILL.md", "# blog\n")
        r = self.sync()
        self.assertEqual(r.returncode, 0)
        self.assertIn("warning: skills/marketing/ is neither operations nor an area key", r.stdout)
        self.assertTrue((self.mirror / "blog" / "SKILL.md").exists())

    def test_the_real_skills_tree(self):
        shutil.rmtree(str(self.ws.root / "skills"))
        shutil.copytree(str(ROOT / "skills"), str(self.ws.root / "skills"))
        r = self.sync()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        canonical = sorted(p.parent.name for p in (self.ws.root / "skills").glob("*/*/SKILL.md"))
        self.assertEqual(sorted(p.name for p in self.mirror.iterdir() if p.is_dir()), canonical)
        self.assertEqual(self.sync("--check").returncode, 0)

    def test_usage_error(self):
        r = self.sync("--force")
        self.assertEqual(r.returncode, 2)
        self.assertIn("Usage: bash tools/skills-sync [--check]", r.stderr)


if __name__ == "__main__":
    unittest.main()
